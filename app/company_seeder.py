def seed_verified_companies(db: Session) -> Dict[str, Any]:
    """
    Seed the database with 100% authentic, verified real software companies and startups.
    Guarantees no synthetic or fake names.
    Never duplicates existing records.
    """
    existing_names = set(row[0].lower() for row in db.query(Company.name).all())
    existing_websites = set(row[0].lower() for row in db.query(Company.website).all())

    inserted = 0
    for item in VERIFIED_REAL_COMPANIES:
        name = item["name"]
        website = item["website"].lower()

        if name.lower() in existing_names or website in existing_websites:
            continue

        company_obj = Company(
            name=item["name"],
            website=item["website"],
            careers_page=item["careers"],
            contact_email=item["email"],
            country=item["country"],
            city=item["city"],
            founded_year=item["year"],
            industry=item["industry"],
            tech_stack=item["stack"],
            remote_policy=item["remote"],
            employee_count=item["size"],
            description=item["desc"],
        )
        db.add(company_obj)
        existing_names.add(name.lower())
        existing_websites.add(website)
        inserted += 1

    db.commit()
    total_count = db.query(Company).count()
    logger.info("Seeded %d authentic companies. Total directory count: %d.", inserted, total_count)
    return {
        "status": "success",
        "total_companies": total_count,
        "newly_inserted": inserted,
    }


def seed_companies(db: Session, target_count: int = 4000) -> Dict[str, Any]:
    """Backward-compatible entry point that seeds only verified real companies."""
    return seed_verified_companies(db)


